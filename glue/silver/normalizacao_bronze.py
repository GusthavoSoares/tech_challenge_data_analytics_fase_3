"""
Normalização da Bronze crua: o primeiro passo da Silver.

A Bronze é cópia fidedigna da origem, sem nenhuma modificação. Quem harmoniza é
a Silver, e este módulo é onde a harmonização começa. Funções de autoria do
Gusthavo.

O que a normalização faz, e por que a Silver precisa dela: a origem traz acento,
espaço e maiúscula em todo valor de texto ("Não", "Cientista de Dados"). Os
de-para da Silver e os rótulos da Gold são escritos sobre a forma normalizada
("Nao", "Cientista_de_Dados").

O de-para de nomes de coluna é POR EDIÇÃO porque a origem muda de convenção:
2023-2024 usa `('P1_a ', 'Idade')` e as duas seguintes usam `1.a_idade`.

A equivalência entre a forma crua e a normalizada está medida em
`docs/VALIDACAO_BRONZE.md` §6.2: 6,7 milhões de células conferidas.
"""

import re
import unicodedata

from pyspark.sql import DataFrame
from pyspark.sql import functions as F
from pyspark.sql.functions import udf
from pyspark.sql.types import StringType


def normalizar_coluna(coluna: str) -> str:
    """Forma canônica de um nome de coluna, usada só para casar com o de-para."""
    if "', '" in coluna:
        coluna = coluna.split("', '", 1)[1]
    coluna = coluna.replace("('", "").replace("')", "").replace('"', "").strip()
    coluna = unicodedata.normalize("NFKD", coluna).encode("ascii", "ignore").decode("utf-8")
    coluna = coluna.lower()
    coluna = re.sub(r"[^a-z0-9_]+", "_", coluna)
    coluna = re.sub(r"_+", "_", coluna).strip("_")
    if coluna and coluna[0].isdigit():
        coluna = "_" + coluna
    return coluna


def normalizar_valor(valor):
    """Tira acento e troca espaço por underline. É o formato que a Silver espera."""
    if valor is None or not isinstance(valor, str):
        return valor
    v = unicodedata.normalize("NFKD", valor).encode("ascii", "ignore").decode("utf-8")
    v = re.sub(r"\s+", "_", v)
    return re.sub(r"__+", "_", v).strip("_")


_udf_normalizar_valor = udf(normalizar_valor, StringType())


def renomear_colunas(df: DataFrame, ano: int) -> DataFrame:
    """
    Aplica o de-para de nomes daquela edição.

    Nome repetido depois do de-para ganha sufixo numérico, e é assim que nascem
    os `_1` que a Silver trata em `grupos_multipla_escolha`: duas perguntas
    diferentes da origem que caem no mesmo nome canônico.
    """
    mapa = NOMES_COLUNAS[ano]
    atuais = df.columns
    usados, finais = {}, []
    for c in atuais:
        canonico = normalizar_coluna(c)
        novo = c
        for chave, valor in mapa.items():
            if canonico == normalizar_coluna(chave) or c == chave:
                novo = valor
                break
        if novo in usados:
            usados[novo] += 1
            novo = f"{novo}_{usados[novo]}"
        else:
            usados[novo] = 0
        finais.append(novo)
    # a crase protege nome de origem com parêntese, espaço e aspas
    return df.select(*[F.col(f"`{atuais[i]}`").alias(finais[i])
                       for i in range(len(atuais))])


def normalizar_valores(df: DataFrame) -> DataFrame:
    """Normaliza o conteúdo de toda coluna string."""
    return df.select(*[
        _udf_normalizar_valor(df[i]).alias(nome) if tipo == "string" else df[i].alias(nome)
        for i, (nome, tipo) in enumerate(df.dtypes)
    ])


